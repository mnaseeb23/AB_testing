/**
 * Output comprehensive Meta tags in <head>
 */
function ljh_output_seo_meta_tags() {
    $site_name = get_bloginfo('name');
    $site_desc = get_bloginfo('description');
    $canonical_url = esc_url(get_permalink());
    $theme_uri = get_template_directory_uri();
    
    // Default meta values
    $meta_title = wp_get_document_title();
    $meta_desc = $site_desc ?: 'Explore premium leather jackets for men and women, including bomber, cafe racer, varsity, biker, and hooded styles crafted for everyday wear.';
    $og_type = 'website';
    $og_image = $theme_uri . '/assets/images/hero-bg.jpg';
    
    if (is_front_page()) {
        $meta_title = 'Leather Jacket House | Premium Leather Jackets for Men & Women';
        $meta_desc = 'Shop luxury handmade leather jackets. Explore premium bomber, biker, cafe racer, varsity, shearling coats, and custom leather outerwear crafted for everyday style.';
    } elseif (is_singular('product') && function_exists('wc_get_product')) {
        global $post;
        $product = wc_get_product($post->ID);
        if ($product) {
            $meta_title = esc_attr($product->get_name()) . ' | Leather Jacket House';
            $meta_desc = wp_strip_all_tags($product->get_short_description() ?: $product->get_description());
            $meta_desc = mb_substr($meta_desc, 0, 160);
            $og_type = 'og:product';
            $image_id = $product->get_image_id();
            if ($image_id) {
                $og_image = wp_get_attachment_image_url($image_id, 'full');
            }
        }
    } elseif (is_singular('post')) {
        global $post;
        $meta_title = esc_attr(get_the_title()) . ' | The Leather Journal';
        $meta_desc = wp_strip_all_tags(get_the_excerpt());
        $og_type = 'article';
        if (has_post_thumbnail()) {
            $og_image = get_the_post_thumbnail_url(get_the_ID(), 'full');
        }
    } elseif (is_post_type_archive('product') || (function_exists('is_shop') && is_shop())) {
        $meta_title = 'Shop Leather Jackets | Men\'s & Women\'s Collection | Leather Jacket House';
        $meta_desc = 'Explore our curated catalog of genuine leather jackets. Bomber, biker, cafe racer, shearling, and luxury coats with free express delivery.';
    }
    
    echo "\n<!-- SEO Meta Tags Generated by Leather Jacket House Theme -->\n";
    echo '<meta name="description" content="' . esc_attr($meta_desc) . '">' . "\n";
    echo '<meta name="keywords" content="leather jacket, men leather jacket, women leather jacket, bomber jacket, biker jacket, cafe racer, shearling coat, varsity jacket, genuine leather">' . "\n";
    echo '<link rel="canonical" href="' . $canonical_url . '">' . "\n";
    echo '<meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1, max-video-preview:-1">' . "\n";
    
    // OpenGraph
    echo '<meta property="og:locale" content="' . esc_attr(get_locale()) . '">' . "\n";
    echo '<meta property="og:type" content="' . esc_attr($og_type) . '">' . "\n";
    echo '<meta property="og:title" content="' . esc_attr($meta_title) . '">' . "\n";
    echo '<meta property="og:description" content="' . esc_attr($meta_desc) . '">' . "\n";
    echo '<meta property="og:url" content="' . $canonical_url . '">' . "\n";
    echo '<meta property="og:site_name" content="' . esc_attr($site_name) . '">' . "\n";
    echo '<meta property="og:image" content="' . esc_url($og_image) . '">' . "\n";
    
    // Twitter Card
    echo '<meta name="twitter:card" content="summary_large_image">' . "\n";
    echo '<meta name="twitter:title" content="' . esc_attr($meta_title) . '">' . "\n";
    echo '<meta name="twitter:description" content="' . esc_attr($meta_desc) . '">' . "\n";
    echo '<meta name="twitter:image" content="' . esc_url($og_image) . '">' . "\n";
    echo "<!-- / SEO Meta Tags -->\n\n";
}
add_action('wp_head', 'ljh_output_seo_meta_tags', 1);

/**
 * Output Schema.org JSON-LD Structured Data
 */
function ljh_output_schema_jsonld() {
    $site_url = esc_url(home_url('/'));
    $site_name = get_bloginfo('name');
    $theme_uri = get_template_directory_uri();
    
    $schemas = [];
    
    // 1. Organization & LocalBusiness Schema
    $schemas[] = [
        '@context' => 'https://schema.org',
        '@type' => 'Store',
        '@id' => $site_url . '#store',
        'name' => $site_name,
        'url' => $site_url,
        'logo' => $theme_uri . '/assets/images/hero-bg.jpg',
        'image' => $theme_uri . '/assets/images/hero-bg.jpg',
        'description' => 'Premium luxury leather outerwear for men and women. Bomber, biker, cafe racer, and varsity jackets.',
        'priceRange' => '$$$',
        'currenciesAccepted' => 'USD, EUR, GBP',
        'paymentAccepted' => 'Cash, Credit Card, Stripe, PayPal, Apple Pay, Google Pay',
        'hasMerchantReturnPolicy' => [
            '@type' => 'MerchantReturnPolicy',
            'applicableCountry' => 'US',
            'returnPolicyCategory' => 'https://schema.org/MerchantReturnFiniteReturnWindow',
            'merchantReturnDays' => 30,
            'returnMethod' => 'https://schema.org/ReturnByMail',
            'returnFees' => 'https://schema.org/FreeReturn'
        ]
    ];
    
    // 2. WebSite SearchAction Schema
    $schemas[] = [
        '@context' => 'https://schema.org',
        '@type' => 'WebSite',
        '@id' => $site_url . '#website',
        'url' => $site_url,
        'name' => $site_name,
        'potentialAction' => [
            '@type' => 'SearchAction',
            'target' => [
                '@type' => 'EntryPoint',
                'urlTemplate' => $site_url . '?s={search_term_string}&post_type=product'
            ],
            'query-input' => 'required name=search_term_string'
        ]
    ];
    
    // 3. Product Schema on Single Product Page
    if (is_singular('product') && function_exists('wc_get_product')) {
        global $post;
        $product = wc_get_product($post->ID);
        if ($product) {
            $image_id = $product->get_image_id();
            $image_url = $image_id ? wp_get_attachment_image_url($image_id, 'full') : $theme_uri . '/assets/images/product-1.jpg';
            
            $product_schema = [
                '@context' => 'https://schema.org',
                '@type' => 'Product',
                '@id' => get_permalink($post->ID) . '#product',
                'name' => $product->get_name(),
                'image' => [$image_url],
                'description' => wp_strip_all_tags($product->get_short_description() ?: $product->get_description()),
                'sku' => $product->get_sku() ?: 'LJH-' . $product->get_id(),
                'brand' => [
                    '@type' => 'Brand',
                    'name' => 'Leather Jacket House'
                ],
                'offers' => [
                    '@type' => 'Offer',
                    'url' => get_permalink($post->ID),
                    'priceCurrency' => get_woocommerce_currency(),
                    'price' => $product->get_price() ?: '895.00',
                    'priceValidUntil' => '2028-12-31',
                    'itemCondition' => 'https://schema.org/NewCondition',
                    'availability' => $product->is_in_stock() ? 'https://schema.org/InStock' : 'https://schema.org/OutOfStock',
                    'seller' => [
                        '@type' => 'Organization',
                        'name' => $site_name
                    ]
                ],
                'aggregateRating' => [
                    '@type' => 'AggregateRating',
                    'ratingValue' => '5.0',
                    'reviewCount' => '5',
                    'bestRating' => '5',
                    'worstRating' => '1'
                ]
            ];
            $schemas[] = $product_schema;
        }
    }
    
    // Output JSON-LD script blocks
    echo "\n<!-- Schema.org JSON-LD Structured Data -->\n";
    foreach ($schemas as $schema) {
        echo '<script type="application/ld+json">' . json_encode($schema, JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT) . '</script>' . "\n";
    }
    echo "<!-- / Schema.org JSON-LD -->\n\n";
}
add_action('wp_head', 'ljh_output_schema_jsonld', 20);

/**
 * Ensure image tags have descriptive alt attributes for SEO
 */
function ljh_ensure_image_alt($attr, $attachment, $size) {
    if (empty($attr['alt'])) {
        $attr['alt'] = get_post_meta($attachment->ID, '_wp_attachment_image_alt', true);
        if (empty($attr['alt'])) {
            $attr['alt'] = get_the_title($attachment->ID) . ' - Genuine Leather Outerwear';
        }
    }
    return $attr;
}
add_filter('wp_get_attachment_image_attributes', 'ljh_ensure_image_alt', 10, 3);
